# Builds the Wii U app: Ruffle -> wasm2c C (gen.ps1), GLSL -> GX2 shaders (CafeGLSL), then devkitPPC + wut
# -> ruffle-wiiu\build-wiiu\flashplayeremu.wuhb.
# Usage: .\build-wiiu.ps1 [-Configure] [-Debug]
param([switch]$Configure, [switch]$Debug)
. "$PSScriptRoot\gen.ps1" -Debug:$Debug
$root = Split-Path $RW

# Shaders: compiled offline, embedded as C arrays in shaders/flashplayer_gsh.c: flashplayer_gsh (drawing)
# and filter_gsh (Flash filters on the GPU; the same vertex shader with filter.frag).
$sh = "$RW\host\wiiu\shaders"
$glslc = "$root\buildtools\cafeglsl\cafeglsl-1.0.0-rc1-windows-x86_64\bin\glslcompiler.exe"
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine("// Generated by tools/build-wiiu.ps1 from shaders/*.vert, *.frag (CafeGLSL). Do not edit.")
[void]$sb.AppendLine("#include <stdint.h>")
foreach ($pair in @(@('flashplayer', 'flashplayer'), @('filter', 'flashplayer'))) {
    $name = $pair[0]
    $gsh = "$sh\$name.gsh"
    $vs = "$sh\$($pair[1]).vert"
    $ps = "$sh\$name.frag"
    if (-not (Test-Path $gsh) -or (Get-Item $vs).LastWriteTime -gt (Get-Item $gsh).LastWriteTime -or
        (Get-Item $ps).LastWriteTime -gt (Get-Item $gsh).LastWriteTime) {
        & $glslc -vs $vs -ps $ps -o $gsh --uniform-mode register
        if ($LASTEXITCODE -ne 0) { throw "shader compile failed: $name" }
    }
    $bytes = [IO.File]::ReadAllBytes($gsh)
    [void]$sb.AppendLine("__attribute__((aligned(256))) const uint8_t $($name)_gsh[$($bytes.Length)] = {")
    for ($i = 0; $i -lt $bytes.Length; $i += 16) {
        $n = [Math]::Min(16, $bytes.Length - $i)
        [void]$sb.AppendLine(($bytes[$i..($i + $n - 1)] | ForEach-Object { '0x{0:x2},' -f $_ }) -join '')
    }
    [void]$sb.AppendLine("};")
}
$gshC = "$sh\flashplayer_gsh.c"
$new = $sb.ToString()
if (-not (Test-Path $gshC) -or [IO.File]::ReadAllText($gshC) -ne $new) { [IO.File]::WriteAllText($gshC, $new) }

# Menu font: Chewy rendered into glyph masks (make-font.ps1), redone when the .ttf or the script changes.
$fontH = "$RW\host\wiiu\font_chewy.h"
$fontSrc = @("$RW\host\wiiu\fonts\Chewy-Regular.ttf", "$PSScriptRoot\make-font.ps1")
if (-not (Test-Path $fontH) -or ($fontSrc | Where-Object { (Get-Item $_).LastWriteTime -gt (Get-Item $fontH).LastWriteTime })) {
    & "$PSScriptRoot\make-font.ps1"
}

function MsysPath($p) { "/" + ($p -replace '\\', '/').Substring(0, 1).ToLower() + ($p -replace '\\', '/').Substring(2) }
$build = "$RW\build-wiiu"
New-Item -ItemType Directory -Force $build | Out-Null
$src = MsysPath "$RW\host\wiiu"
$bld = MsysPath $build
$cmd = "source /etc/profile.d/devkit-env.sh; "
if ($Configure -or -not (Test-Path "$build\Makefile")) {
    $cmd += "/opt/devkitpro/portlibs/wiiu/bin/powerpc-eabi-cmake -S '$src' -B '$bld' -G 'Unix Makefiles' -DCMAKE_BUILD_TYPE=Release > '$bld/configure.log' 2>&1 || { tail -30 '$bld/configure.log'; exit 1; }; "
}
$cmd += "make -C '$bld' -k -j8 > '$bld/build.log' 2>&1"
$env:MSYSTEM = 'MSYS'
$env:CHERE_INVOKING = '1'
& "$root\buildtools\msys64\usr\bin\bash.exe" -lc $cmd
$code = $LASTEXITCODE
$errors = Get-Content "$build\build.log" -ErrorAction SilentlyContinue | Select-String ' error:|undefined reference|Error [0-9]'
"exit $code, errors: $($errors.Count)"
$errors | Select-Object -First 30 | ForEach-Object { "  $($_.Line)" }
$wuhb = "$build\flashplayeremu.wuhb"
if (Test-Path $wuhb) { "wuhb: $wuhb ({0:N1} MB)" -f ((Get-Item $wuhb).Length / 1MB) }
if ($code -ne 0) { exit $code }
